'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const execFile = require('node:util').promisify(require('node:child_process').execFile);
const { startSshFixture } = require('./ssh_test_server.cjs');

module.exports = async function checkTerminalRestore({ getPage, launch, close, app, dir, a, until }) {
  const server = await startSshFixture(path.join(dir, 'restore-ssh'));
  let page = getPage();
  const { port, password, fingerprint } = server.data;
  const shellDirectory = path.join(a, 'shell'), movedDirectory = path.join(a, 'moved-shell');
  const counts = () => { server.tell('session-counts'); return server.next(); };
  const snapshot = () => page.evaluate(() => store.get('workspaceSession', null));
  const select = index => page.locator('#tabViewport .tab[data-t="' + index + '"]').click();
  const signIn = async () => {
    await page.locator('#sshPassword').fill(password);
    await page.locator('#sshRememberSecret').uncheck();
    await page.locator('#sshConnect').click();
    await page.waitForFunction(() => curTab()?.sshAuthenticated && curTab().sshFiles?.historyWorkspace);
  };
  try {
    await fs.mkdir(shellDirectory);
    const probe = await page.evaluate(port => invoke('ssh_probe_host', { config: { host: '127.0.0.1', port, user: 'fixture', infoMode: 'shell' } }), port);
    assert.equal(probe.previous, null);
    assert.equal(probe.fingerprint, fingerprint);
    server.tell('allow-cleanup');
    await page.evaluate(token => invoke('ssh_trust_host', { token }), probe.token);
    await page.evaluate(async ({folder, shellDirectory}) => {
      await navigate(folder);
      await newTermTab(shellDirectory);
      await invoke('term_write', { id: curTab().termId, data: "Set-Content -LiteralPath 'mixed-run.txt' -Value 'first-session'\r" });
    }, {folder: a, shellDirectory});
    const marker = path.join(shellDirectory, 'mixed-run.txt');
    await until(async () => (await fs.readFile(marker, 'utf8').catch(() => '')).trim() === 'first-session');
    await page.evaluate(async () => { await newBrowserTab('about:blank'); openSshConnect(); });
    await page.locator('#sshHost').fill('127.0.0.1');
    await page.locator('#sshPort').fill(String(port));
    await page.locator('#sshUser').fill('fixture');
    await page.locator('#sshLabel').fill('Restore fixture');
    await page.locator('#sshMode').selectOption('shell');
    await signIn();
    await page.waitForFunction(() => !!curTab().sshProfileId);
    const saved = await snapshot();
    assert.deepEqual(saved.tabs.map(t => t.kind), ['files', 'terminal', 'browser', 'ssh']);
    assert.deepEqual(saved.tabs[1], { kind: 'terminal', cwd: shellDirectory });
    assert.deepEqual(Object.keys(saved.tabs[3]).sort(), ['kind', 'profileId']);
    assert.equal(saved.active, 3);
    assert.equal(JSON.stringify(saved).includes(password), false);
    const before = await counts();
    await execFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command',
      'if (!(Get-Process -Id ' + app.pid + ').CloseMainWindow()) { exit 1 }'], { windowsHide: true, timeout: 10000 });
    await until(() => app.exitCode !== null);
    assert.equal(app.exitCode, 0);
    await close(); await launch(); page = getPage();
    assert.deepEqual((await snapshot()).tabs, saved.tabs);
    assert.equal(await page.evaluate(() => state.tab), 3);
    await page.locator('#pendingTerminalStart').waitFor();
    assert.equal(await page.evaluate(() => state.tabs[2].browserReady), false);
    assert.ok(await page.evaluate(() => state.tabs.filter(isTermTab).every(t => t.pendingTerminal && t.termId === null && !t.term)));
    await select(1); await select(3);
    await page.locator('#pendingTerminalStart').click();
    assert.equal(await page.locator('#sshPort').inputValue(), String(port));
    assert.equal(await page.locator('#sshPassword').inputValue(), '');
    await page.locator('[data-ssh-dialog=close]').click();
    await page.evaluate(() => closeTab(state.tab));
    await page.locator('#tabReopen').click();
    assert.equal(await page.evaluate(() => curTab().sshProfileId), saved.tabs[3].profileId);
    assert.deepEqual(await counts(), before, 'restore, focus, cancel and reopen may not contact SSH');
    await page.locator('#pendingTerminalStart').click();
    await page.locator('#sshPassword').fill('deliberately-wrong-fixture-password');
    await page.locator('#sshRememberSecret').uncheck();
    await page.locator('#sshConnect').click();
    await page.waitForFunction(() => sshDialog.open && !sshDialogBusy && curTab().pendingTerminal && !!curTab().sshError);
    assert.equal(await page.locator('#sshPassword').inputValue(), '');
    assert.equal(await page.locator('#sshRememberSecret').isChecked(), false);
    assert.equal(await page.evaluate(() => state.tabs.length), 4);
    await signIn();
    assert.ok((await counts()).authAttempts > before.authAttempts);
    assert.equal(await page.evaluate(() => state.tab === 3 && state.tabs.length === 4), true);
    assert.equal(await page.evaluate(() => readSshProfiles().length), 1);
    await fs.rename(shellDirectory, movedDirectory);
    await select(1); await page.locator('#pendingTerminalStart').click();
    await page.waitForFunction(() => curTab().pendingTerminal && !!curTab().sshError);
    assert.ok((await page.locator('#pendingTerminalError').innerText()).includes(shellDirectory));
    await fs.rename(movedDirectory, shellDirectory);
    await page.locator('#pendingTerminalStart').click();
    await page.waitForFunction(() => curTab().termId != null && !curTab().starting);
    assert.equal(await page.evaluate(() => state.tabs.length), 4);
    await page.evaluate(() => invoke('term_write', { id: curTab().termId, data: "Set-Content -LiteralPath 'mixed-restarted.txt' -Value 'new-session'\r" }));
    await until(async () => (await fs.readFile(path.join(shellDirectory, 'mixed-restarted.txt'), 'utf8').catch(() => '')).trim() === 'new-session');
    await page.evaluate(() => closeTab(state.tab));
    await page.locator('#tabReopen').click();
    assert.ok(await page.evaluate(() => state.tab === 1 && curTab().pendingTerminal && !curTab().term));
    await select(3);
    await page.evaluate(async () => {
      await closeTab(state.tab);
      const profile = readSshProfiles()[0];
      openSshConnect(profile);
    });
    await page.locator('#sshRemember').uncheck();
    await signIn();
    assert.deepEqual((await snapshot()).tabs[3], { kind: 'ssh', profileId: null });
    await page.evaluate(() => closeTab(state.tab));
    await page.locator('#tabReopen').click();
    await page.locator('#pendingTerminalStart').click();
    assert.equal(await page.locator('#sshHost').inputValue(), '');
    assert.equal(await page.locator('#sshRemember').isChecked(), false);
    await page.locator('[data-ssh-dialog=close]').click();
    console.log('Mixed workspace OK: normal exit, four-tab order and focus, no SSH network activity during recovery, explicit in-place login and PowerShell, private connection and closed-tab position.');
  } finally {
    await close();
    await server.stop();
  }
};
