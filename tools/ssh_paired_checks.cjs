const assert = require('node:assert/strict');
module.exports = async page => {
  const active=page.locator('.term.ssh-terminal-host:visible'), layout=active.locator('[data-ssh-layout=paired]');
  const local=active.locator('.ssh-local-pane');
  // This tab has authenticated SFTP and no shell.
  await layout.click();
  assert.equal(await layout.getAttribute('aria-pressed'),'true');
  assert.equal(await local.locator('[data-local-path]').inputValue(),'');
  await page.evaluate(()=>{
    window.pairA=curTab();
    window.mockListDeferred=true;
    void loadSshLocalFolder(pairA,'D:\\slow');
  });
  await page.waitForFunction(()=>typeof resolveMockList==='function');
  await page.evaluate(async()=>{
    mockListDeferred=false;
    const make=name=>({name,isDir:false,isReparse:false,size:4});
    window.mockEntries=[...Array.from({length:104},(_,i)=>make('file-'+(i+1))),{...make('linked'),isReparse:true}];
    await loadSshLocalFolder(pairA,'D:\\reviewed');
    resolveMockList();
  });
  assert.equal(await local.locator('[data-local-path]').inputValue(),'D:\\reviewed');
  assert.equal(await local.locator('[data-local-name]').count(),100);
  await local.locator('[data-local-next]').click();
  assert.equal(await local.locator('[data-local-name="linked"]').isDisabled(),true);
  await local.locator('[data-local-filter]').fill('file-10');
  await local.locator('[data-local-name="file-10"]').click();
  await page.evaluate(()=>{window.mockPreviewDeferred=true;});
  await local.locator('[data-pane-preview=local]').click();
  await page.waitForFunction(()=>typeof resolveMockPreview==='function');
  await local.locator('[data-local-name="file-102"]').click({modifiers:['Shift']});
  await page.evaluate(()=>{mockPreviewDeferred=false;resolveMockPreview();});
  assert.equal(await local.locator('[data-preview-side=local]').isVisible(),false);
  assert.deepEqual(await page.evaluate(()=>[...pairA.sshFiles.localPane.selection]),['file-10','file-100','file-101','file-102']);
  await page.evaluate(()=>{
    const view=pairA.sshFiles;
    view.entries=['a-hit','b-skip','c-hit'].map(name=>({name,isDir:false,isLink:false,size:7}));
    renderSshFiles(pairA,'3');
  });
  await active.locator('[data-remote-filter]').fill('hit');
  await active.locator('.ssh-file-row').first().click();
  await active.locator('.ssh-file-row').last().click({modifiers:['Shift']});
  await active.locator('[data-download]').click();
  await page.locator('#sshBatchReview[open]').waitFor();
  assert.deepEqual(await page.locator('#sshBatchReview li strong').allTextContents(),['a-hit','c-hit']);
  await page.locator('[data-batch-close]').first().click();
  const pickers=()=>page.evaluate(()=>mockCalls.filter(c=>['ssh_pick_download_directory','ssh_pick_upload_files'].includes(c.cmd)).length);
  const before=await pickers();
  await page.evaluate(()=>{window.mockPrepareDeferred=true;});
  await local.locator('[data-local-upload]').click();await page.waitForFunction(()=>typeof resolveMockPrepare==='function');
  await page.evaluate(async()=>{window.pairB=await newSshTab({host:'pair-b.test',user:'other',managed:true,infoMode:'posix'});});
  await page.waitForFunction(()=>curTab()===pairB && pairB.sshFiles?.ready);
  await layout.click();
  assert.equal(await local.locator('[data-local-path]').inputValue(),'','a new SSH tab has its own local selection');
  await page.evaluate(()=>{mockPrepareDeferred=false; resolveMockPrepare();});
  await page.waitForFunction(()=>!pairA.sshBatchPicking);
  assert.equal(await page.locator('#sshBatchReview[open]').count(),0,'late prepare cannot open over another host');
  assert.equal(await pickers(),before);
  await page.evaluate(()=>switchTab(state.tabs.indexOf(pairA)));
  assert.equal(await local.locator('[data-local-path]').inputValue(),'D:\\reviewed');
  assert.equal(await local.locator('[data-local-name][aria-selected=true]').count(),4);
  assert.equal(await page.evaluate(()=>tabLocalFolder(pairA)),null);
  await local.locator('[data-local-workspace]').click();
  await page.waitForFunction(()=>fileListingReady() && tabLocalFolder(curTab())==='D:\\reviewed');
  assert.equal(await page.evaluate(()=>pairA.sshFiles.path),'/data');
  await page.evaluate(()=>switchTab(state.tabs.indexOf(pairA)));
  await active.locator('.ssh-paired-more summary').click();
  await active.locator('[data-tasks]').click(); await page.locator('#sshTaskCenter[open]').waitFor();
  await page.locator('[data-tasks-close]').last().click();
  await active.locator('[data-ssh-layout=files]').click();
  assert.equal(await active.locator('[data-tasks]').isVisible(),true);
  assert.equal(await local.isVisible(),false);
  await page.evaluate(()=>{window.mockEntries=null;});
};
