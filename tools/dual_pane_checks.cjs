const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async (page, output) => {
  await page.waitForFunction(() => typeof toggleDualPane === 'function' && typeof initAiAssistant === 'function');
  await page.evaluate(async () => { await navigate('C:\\Projects'); toggleDualPane(true); });
  await page.waitForFunction(() => companionFor()?.entries.length > 0 && !companionFor().loading);
  await page.evaluate(() => { window.mainSizeLookup=state.sizeEntries; });
  await page.locator('#companionPane [data-path]').fill('C:\\Other');
  await page.locator('#companionPane form').evaluate(f => f.requestSubmit());
  await page.waitForFunction(() => companionFor()?.path === 'C:\\Other' && !companionFor().loading);
  assert.equal(await page.evaluate(() => state.path), 'C:\\Projects', 'companion navigation must not change AI scope');
  assert.equal(await page.evaluate(() => state.sizeEntries === mainSizeLookup), true, 'companion leaves main folder size updates intact');
  const file = page.locator('.pane-file').filter({ hasText: 'Project-notes-1.md' });
  await file.click();
  assert.equal(await page.evaluate(() => state.selection.size), 0, 'companion selection is independent');
  await page.locator('#companionPane [data-to-left]').click();
  assert.match(await page.locator('.drop-destination').textContent(), /Projects/);
  assert.match(await page.locator('.drop-files').textContent(), /Other/);
  await page.locator('[data-drop-close]').last().click();
  await page.locator('#companionPane [data-work]').click();
  await page.waitForFunction(() => state.path === 'C:\\Other' && companionFor()?.path === 'C:\\Projects' && !companionFor().loading);
  assert.equal(await page.evaluate(() => state.selection.has('Project-notes-1.md')), true);
  const owner = await page.evaluate(() => state.tab);
  await page.evaluate(() => newTab('C:\\Elsewhere'));
  assert.equal(await page.locator('#companionPane').isVisible(), false, 'new tabs do not inherit other tabs companion');
  await page.evaluate(i => switchTab(i), owner); await page.waitForFunction(() => !state.loading);
  assert.equal(await page.locator('#companionPane').isVisible(), true);
  assert.equal(await page.evaluate(() => companionFor().path), 'C:\\Projects');
  await page.evaluate(() => { companionFor().entries = Array.from({length:10000},(_,i)=>({name:`row-${i}.txt`,isDir:false})); syncDualPane(); });
  assert.ok(await page.locator('.pane-file').count() < 60, 'companion list is virtualized');
  await page.evaluate(() => { document.documentElement.dataset.theme='dark'; });
  await page.setViewportSize({width:960,height:560});
  await page.screenshot({path:path.join(output,'dual-pane-compact.png'),animations:'disabled'});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await page.locator('#companionPane').evaluate(el=>getComputedStyle(el).color), 'rgb(232, 237, 247)');
  assert.equal(await page.locator('#companionPane [data-scope]').evaluate(el=>el.getBoundingClientRect().bottom<=document.querySelector('#companionPane').getBoundingClientRect().bottom),true,'AI scope hint remains visible in a small window');
  await page.setViewportSize({width:854,height:534});
  assert.ok(await page.locator('.pane-list').evaluate(el=>el.clientHeight)>=48,'high-DPI viewport keeps a usable file list');
  await page.screenshot({path:path.join(output,'dual-pane-high-dpi.png'),animations:'disabled'});
  // Resolve an older request after a newer one; only the current directory may win.
  await page.evaluate(async () => {
    window.mockListDeferred=true; window.paneOld=loadCompanion('C:\\Old');
    const resolveOld=window.resolveMockList; window.mockListDeferred=false;
    window.mockEntries=[{name:'new.txt'}]; await loadCompanion('C:\\New');
    window.mockEntries=[{name:'old.txt'}]; resolveOld(); await paneOld; window.mockEntries=null;
  });
  assert.equal(await page.evaluate(() => companionFor().path), 'C:\\New');
  assert.equal(await page.evaluate(() => companionFor().entries[0].name), 'new.txt');
};
